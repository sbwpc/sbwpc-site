// Drives the admin screens in a real browser against the local database copy, under the live security headers.
import fs from 'node:fs'
import {startSite} from './site.mjs'
import {open, fakeSupabase, signIn, shot, DESK, PHONE, OUT} from './browser.mjs'

const site = await startSite()
const {origin, sql} = site
let pass = 0, failed = 0
const ok = (name, cond, detail = '') => { cond ? pass++ : failed++; console.log(`${cond ? 'PASS' : 'FAIL'}  ${name}${cond ? '' : '  -> ' + detail}`) }
const text = (page, sel) => page.locator(sel).first().innerText()
const colValues = (page, label) => page.$$eval(`#app table tbody td[data-label="${label}"]`, (tds) => tds.map((t) => t.innerText.trim()))

async function run(name, opts, full) {
  const {browser, page, errors} = await open(opts)
  await fakeSupabase(page, 'luke@coolhandlook.com')
  page.on('dialog', (d) => d.accept())
  await signIn(page, origin)
  await shot(page, `admin-${name}-1-overview`)
  if (full) {
    const tiles = await page.$$eval('.a-tile', (t) => t.map((x) => x.innerText.replace(/\n+/g, ' ')))
    const dbActive = (await sql(`select count(*)::int n from public.membership_status where status in ('active','expiring_soon')`))[0].n
    ok('overview tiles match the database', tiles[0].startsWith(dbActive + ' ') && /Checks to confirm/.test(tiles[6]) && tiles[6].startsWith('3 '), tiles.join(' | '))
  }

  // Members: search, filter, sort
  await page.click('.a-nav a[data-nav=members]')
  await page.waitForSelector('#app table')
  await shot(page, `admin-${name}-2-members`, full)
  if (full) {
    ok('members list shows every membership', (await text(page, '.a-count')) === '32 memberships', await text(page, '.a-count'))
    await page.fill('#app input[name=q]', 'alvarez')
    ok('search by name narrows the list', (await text(page, '.a-count')) === '1 membership' && (await colValues(page, 'Name'))[0] === 'Maria Alvarez')
    await page.fill('#app input[name=q]', 'DANA.BENNETT@example.com')
    ok('search by email works, any letter case', (await colValues(page, 'Name')).join() === 'Dana Bennett')
    await page.fill('#app input[name=q]', '')
    await page.selectOption('#app select[name=status]', 'expiring_soon')
    const exp = await sql(`select count(*)::int n from public.membership_status where status = 'expiring_soon'`)
    ok('filter by status: expiring soon', (await text(page, '.a-count')).startsWith(exp[0].n + ' ') && (await colValues(page, 'Status')).every((s) => s === 'Expiring soon'))
    await page.selectOption('#app select[name=status]', 'expired')
    ok('filter by status: expired', (await colValues(page, 'Status')).every((s) => s === 'Expired') && (await colValues(page, 'Status')).length === 3)
    await page.selectOption('#app select[name=status]', '')
    await page.selectOption('#app select[name=level]', 'Advocate')
    ok('filter by level', (await colValues(page, 'Level')).every((s) => s === 'Advocate') && (await colValues(page, 'Level')).length > 3)
    await page.selectOption('#app select[name=level]', '')
    await page.selectOption('#app select[name=committee]', 'Media')
    ok('filter by committee', (await colValues(page, 'Committees')).every((s) => s.includes('Media')) && (await colValues(page, 'Committees')).length > 0)
    await page.selectOption('#app select[name=committee]', '')
    await page.click('#app th button:has-text("Expires")')
    let d = (await colValues(page, 'Expires')).filter(Boolean).map((x) => new Date(x).getTime())
    ok('sort by expiration date, soonest first', d.every((v, i) => !i || d[i - 1] <= v))
    await page.click('#app th button:has-text("Expires")')
    d = (await colValues(page, 'Expires')).filter(Boolean).map((x) => new Date(x).getTime())
    ok('press again to reverse the sort', d.every((v, i) => !i || d[i - 1] >= v))
    for (const col of ['Name', 'Email', 'Level', 'Status', 'Auto-renew', 'Committees']) await page.click(`#app th button:has-text("${col}")`)
    ok('every column heading sorts', (await page.getAttribute('#app th:has(button:has-text("Committees"))', 'aria-sort')) === 'ascending')
    await page.click('#app th button:has-text("Name")')
    const dl = page.waitForEvent('download')
    await page.click('button:has-text("Download these")')
    const csv = fs.readFileSync(await (await dl).path(), 'utf8')
    ok('members download has contact, level and dates for every row', csv.split('\r\n').length === 34 && csv.includes('Last name,First name,Email') && csv.includes('Alvarez,Maria,maria.alvarez@example.com'), csv.slice(0, 200))
    await page.selectOption('#app select[name=status]', 'expiring_soon')
    await shot(page, `admin-${name}-3-members-expiring`)
    await page.selectOption('#app select[name=status]', '')
  }

  // Donors and payments
  await page.click('.a-nav a[data-nav=payments]')
  await page.waitForSelector('#app table')
  await shot(page, `admin-${name}-4-payments`, full)
  if (full) {
    const dbPay = (await sql(`select count(*)::int n, sum(amount_cents)::int s from public.payments`))[0]
    ok('payments list and total match the database', (await text(page, '.a-count')) === `${dbPay.n} payments, $${(dbPay.s / 100).toLocaleString('en-US')} total`, await text(page, '.a-count'))
    await page.selectOption('#app select[name=kind]', 'donation')
    ok('filter by type', (await colValues(page, 'Type')).every((s) => s === 'Donation'))
    await page.fill('#app input[name=min]', '100')
    ok('filter by amount', (await colValues(page, 'Amount')).every((s) => Number(s.replace(/[$,]/g, '')) >= 100) && (await colValues(page, 'Amount')).length > 0)
    await page.fill('#app input[name=min]', '')
    await page.selectOption('#app select[name=kind]', '')
    const from = new Date(Date.now() - 30 * 86400000).toISOString().slice(0, 10)
    await page.fill('#app input[name=from]', from)
    const recent = (await sql(`select count(*)::int n from public.payments where paid_on >= $1`, [from]))[0].n
    ok('filter by date', (await text(page, '.a-count')).startsWith(recent + ' '))
    await page.fill('#app input[name=from]', '')
    await page.click('#app th button:has-text("Amount")')
    const a = (await colValues(page, 'Amount')).map((s) => Number(s.replace(/[$,]/g, '')))
    ok('sort by amount, largest first', a.every((v, i) => !i || a[i - 1] >= v))
    await page.check('#app input[name=flag]')
    ok('"$100 or more" filter keeps only flagged people', (await colValues(page, 'Total for the year')).every((s) => s.includes('$100+ report')))
    await page.uncheck('#app input[name=flag]')
    await page.click('.a-tab:has-text("Totals by person")')
    await page.waitForSelector('#app th button:has-text("Donations")')
    const flagged = (await sql(`select count(*)::int n from public.contributor_totals where reportable and year = extract(year from public.today_pt())`))[0].n
    await page.check('#app input[name=flag]')
    ok('totals by person: flagged count matches the database', (await text(page, '.a-count')).startsWith(flagged + ' '), await text(page, '.a-count'))
    await shot(page, `admin-${name}-5-totals-by-person`)
    await page.uncheck('#app input[name=flag]')
    await page.click('.a-nav a[href="#/"]')
    await page.waitForSelector('.a-tiles')
    let dl = page.waitForEvent('download')
    await page.click(`button:has-text("Payments with FPPC details, ${new Date().getFullYear()}")`)
    const csv = fs.readFileSync(await (await dl).path(), 'utf8')
    ok('payments download carries the FPPC fields and running totals', csv.includes('Street address,City,State,ZIP,Occupation,Employer,Amount') && csv.includes('Cumulative for the year') && csv.includes('$100 or more (reportable)'))
    dl = page.waitForEvent('download')
    await page.click('button:has-text("Email list")')
    const emails = fs.readFileSync(await (await dl).path(), 'utf8').trim().split('\r\n')
    const optin = await sql(`select email::text from public.people where email_opt_in and email is not null`)
    const optout = await sql(`select email::text from public.people where not email_opt_in`)
    ok('email list holds only people who gave permission', emails.length - 1 === optin.length && optout.every((p) => !emails.join('\n').includes(p.email)))
    await page.click('.a-nav a[data-nav=payments]')
  } else {
    await page.click('.a-tab:has-text("Totals by person")')
    await shot(page, `admin-${name}-5-totals-by-person`, false)
    await page.click('.a-nav a[data-nav=members]')
    await page.selectOption('#app select[name=sortby]', 'expires')
    const d = (await colValues(page, 'Expires')).filter(Boolean).map((x) => new Date(x).getTime())
    ok('phone: the "Sort by" menu sorts the cards', d.length > 5 && d.every((v, i) => !i || d[i - 1] <= v))
  }

  // Checks to confirm
  await page.click('.a-nav a[data-nav=checks]')
  await page.waitForSelector('#app table')
  await shot(page, `admin-${name}-6-checks`)
  if (full) {
    await page.click('#app tr:has-text("Winnie Okafor") button:has-text("Mark received")')
    await page.fill('.a-inline-form input[name=note]', 'Check 5512')
    await shot(page, `admin-${name}-7-check-received`)
    await page.click('.a-inline-form button[type=submit]')
    await page.waitForSelector('h1:has-text("Winnie Okafor")')
    const w = (await sql(`select m.level, m.state, y.method, y.note, y.amount_cents, y.created_by, c.status from public.people p join public.memberships m on m.person_id = p.id join public.payments y on y.person_id = p.id join public.checkouts c on c.payment_id = y.id where p.email = 'winnie.okafor@example.com'`))[0]
    ok('marking a check received creates the member and the payment', w && w.level === 'Access' && w.state === 'active' && w.method === 'check' && w.note === 'Check 5512' && w.amount_cents === 12500 && w.created_by === 'luke@coolhandlook.com' && w.status === 'completed', JSON.stringify(w))
    ok('the checks badge counts down', (await text(page, '#nav-checks-n')) === '2')
    await page.click('.a-nav a[data-nav=checks]')
    await page.click('#app tr:has-text("Harriet Lindqvist") button:has-text("Cancel")')
    await page.waitForFunction(() => !document.querySelector('#app')?.innerText.includes('Harriet Lindqvist'))
    ok('a cancelled check leaves no person or payment', (await sql(`select status from public.checkouts where payload->>'last_name' = 'Lindqvist'`))[0].status === 'cancelled' && (await sql(`select count(*)::int n from public.people where last_name = 'Lindqvist'`))[0].n === 0)
    await page.click('#app tr:has-text("Maria Alvarez") button:has-text("Mark received")')
    await page.click('.a-inline-form button[type=submit]')
    await page.waitForSelector('h1:has-text("Maria Alvarez")')
    ok('a check from an existing member renews her, no duplicate', (await sql(`select count(*)::int n from public.people where last_name = 'Alvarez'`))[0].n === 1 && (await sql(`select count(*)::int n from public.memberships m join public.people p on p.id = m.person_id where p.last_name = 'Alvarez'`))[0].n === 1)
  }

  // Person page
  await page.click('.a-nav a[data-nav=members]')
  await page.fill('#app input[name=q]', 'alvarez')
  await page.click('#app a.a-name')
  await page.waitForSelector('h1:has-text("Maria Alvarez")')
  await page.waitForFunction(() => !document.querySelector('#app').innerText.includes('Loading...'))
  await shot(page, `admin-${name}-8-person`)
  if (full) {
    const body = await text(page, '#app')
    const noteText = await page.locator('#app textarea').inputValue()
    ok('person page shows contact, membership, payments, notes and history', ['maria.alvarez@example.com', 'Teacher', 'Santa Barbara Unified', 'Membership', 'Payments', 'Change history', 'Check'].every((s) => body.includes(s)) && noteText.includes('Prefers phone calls'), body.slice(0, 300))
    await page.fill('#app textarea', 'Prefers phone calls. Wants to join the Media committee.')
    await page.click('button:has-text("Save notes")')
    await page.waitForSelector('#a-flash:not([hidden])')
    ok('notes save', (await sql(`select notes from public.people where last_name = 'Alvarez'`))[0].notes.includes('Media committee'))

    await page.click('a:has-text("Edit details")')
    await page.waitForSelector('#app form')
    await page.fill('#app input[name=phone]', '805-555-0199')
    await page.fill('#app input[name=employer]', 'Goleta Union School District')
    await shot(page, `admin-${name}-9-edit-person`)
    await page.click('#app form button[type=submit]')
    await page.waitForSelector('h1:has-text("Maria Alvarez")')
    const audit = (await sql(`select actor, before->>'phone' b, after->>'phone' a from public.audit_log where table_name = 'people' and action = 'update' and after->>'phone' = '805-555-0199' order by at desc limit 1`))[0]
    ok('editing a person saves and is written to the audit log with who did it', audit && audit.actor === 'luke@coolhandlook.com' && audit.b !== audit.a, JSON.stringify(audit))

    const before = (await sql(`select expires_on::text e from public.memberships m join public.people p on p.id = m.person_id where p.last_name = 'Bennett'`))[0].e
    await page.click('.a-nav a[data-nav=members]')
    await page.fill('#app input[name=q]', 'bennett')
    await page.click('#app a.a-name')
    await page.click('a:has-text("Record a payment")')
    await page.waitForSelector('#app form')
    await page.fill('#app input[name=note]', 'Check 3301')
    await shot(page, `admin-${name}-10-record-payment`)
    await page.click('#app form button[type=submit]')
    await page.waitForSelector('#a-flash:not([hidden])')
    const after = (await sql(`select expires_on::text e from public.memberships m join public.people p on p.id = m.person_id where p.last_name = 'Bennett'`))[0].e
    ok('recording a check by hand extends the membership a year', Number(after.slice(0, 4)) === Number(before.slice(0, 4)) + 1 && (await sql(`select count(*)::int n from public.payments where note = 'Check 3301' and method = 'check' and source = 'manual'`))[0].n === 1, `${before} -> ${after}`)

    await page.click('a:has-text("Edit membership")')
    await page.waitForSelector('#app form')
    await page.selectOption('#app select[name=level]', 'Voice')
    await page.check('#app input[value="Young Femmes"]')
    await shot(page, `admin-${name}-11-edit-membership`)
    await page.click('#app form button[type=submit]')
    await page.waitForSelector('#a-flash:not([hidden])')
    const mm = (await sql(`select level, committees from public.memberships m join public.people p on p.id = m.person_id where p.last_name = 'Bennett'`))[0]
    ok('editing a membership saves', mm.level === 'Voice' && mm.committees.includes('Young Femmes'))
    await page.click('#app table[aria-label=Payments] a:has-text("Edit")')
    await page.waitForSelector('#app form')
    await page.selectOption('#app select[name=status]', 'failed')
    await page.click('#app form button[type=submit]')
    await page.waitForSelector('#a-flash:not([hidden])')
    ok('a bounced check can be marked failed and drops out of the totals', (await sql(`select count(*)::int n from public.payments y join public.people p on p.id = y.person_id where p.last_name = 'Bennett' and status = 'failed'`))[0].n === 1)

    // Add a person by hand, with their check
    await page.click('#nav-new')
    await page.waitForSelector('#app form')
    await page.click('#app form button[type=submit]')
    ok('add a person: empty form is stopped with a message', (await text(page, '#app .a-error')).includes('name'))
    await page.fill('#app input[name=first_name]', 'Lorraine'); await page.fill('#app input[name=last_name]', 'Whitfield')
    await page.fill('#app input[name=email]', 'maria.alvarez@example.com')
    await page.click('#app form button[type=submit]')
    ok('add a person: an email already on file is caught, no duplicate', (await text(page, '#app .a-error')).includes('already on file'))
    await page.fill('#app input[name=email]', 'lorraine.w@example.com')
    await page.fill('#app input[name=address1]', '4 Laurel Canyon Rd'); await page.fill('#app input[name=city]', 'Santa Barbara'); await page.fill('#app input[name=zip]', '93105')
    await page.fill('#app input[name=occupation]', 'Retired'); await page.fill('#app input[name=employer]', 'None')
    await page.selectOption('#app select[name=kind]', 'dues')
    await page.selectOption('#app select[name=level]', 'Power')
    await page.fill('#app input[name=note]', 'Check 118')
    await shot(page, `admin-${name}-12-add-person`)
    await page.click('#app form button[type=submit]')
    await page.waitForSelector('h1:has-text("Lorraine Whitfield")')
    const lw = (await sql(`select p.source, m.level, m.state, y.amount_cents, y.method, y.note from public.people p join public.memberships m on m.person_id = p.id join public.payments y on y.person_id = p.id where p.last_name = 'Whitfield'`))[0]
    ok('add a person with a check: person, membership and payment created together', lw && lw.source === 'manual' && lw.level === 'Power' && lw.state === 'active' && lw.amount_cents === 50000 && lw.method === 'check' && lw.note === 'Check 118', JSON.stringify(lw))
    await page.waitForFunction(() => !document.querySelector('#app').innerText.includes('Loading...'))
    await shot(page, `admin-${name}-13-new-person-page`)
    await page.click('#nav-new')
    await page.fill('#app input[name=first_name]', 'Only'); await page.fill('#app input[name=last_name]', 'Contact')
    await page.click('#app form button[type=submit]')
    await page.waitForSelector('h1:has-text("Only Contact")')
    ok('add a person with no payment', (await sql(`select count(*)::int n from public.payments y join public.people p on p.id = y.person_id where p.last_name = 'Contact'`))[0].n === 0)
    ok('every change above is in the audit log', (await sql(`select count(*)::int n from public.audit_log where actor = 'luke@coolhandlook.com'`))[0].n >= 10)
  }
  ok(`${name}: no script errors and nothing blocked by the security headers`, errors.length === 0, errors.join(' || '))
  await page.click('#a-signout')
  await page.waitForSelector('#v-signin:not([hidden])')
  ok(`${name}: signing out clears the screen and the session`, (await page.evaluate(() => document.getElementById('app').childElementCount + Object.keys(sessionStorage).length)) === 0)
  await browser.close()
}

await run('phone', PHONE, false)
await run('desktop', DESK, true)

// A treasurer can look but not change. The database refuses even if the buttons were forced.
{
  const {browser, page, errors} = await open(DESK)
  await fakeSupabase(page, 'treasurer@example.com')
  await signIn(page, origin)
  ok('treasurer: no add button', await page.locator('#nav-new').isHidden())
  await page.click('.a-nav a[data-nav=checks]')
  ok('treasurer: no check actions', (await page.locator('#app button:has-text("Mark received")').count()) === 0)
  await page.goto(origin + '/admin/#/new')
  await page.waitForSelector('h1:has-text("View only")')
  const {jwt} = await import('./browser.mjs')
  const tryWrite = await fetch('http://localhost:54330/rest/v1/people', {method: 'POST', headers: {authorization: 'Bearer ' + jwt('treasurer@example.com'), 'content-type': 'application/json', prefer: 'return=representation'}, body: JSON.stringify({first_name: 'X', last_name: 'Y'})})
  ok('treasurer: the database itself refuses a write', tryWrite.status === 403)
  const noMfa = await fetch('http://localhost:54330/rest/v1/people?select=*', {headers: {authorization: 'Bearer ' + jwt('luke@coolhandlook.com', 'aal1')}})
  ok('an admin without the two-factor step sees no records', (await noMfa.json()).length === 0)
  const stranger = await fetch('http://localhost:54330/rest/v1/people?select=*', {headers: {authorization: 'Bearer ' + jwt('stranger@example.com')}})
  ok('a signed-in stranger sees no records', (await stranger.json()).length === 0)
  const strangerChecks = await fetch('http://localhost:54330/rest/v1/checkouts?select=*', {headers: {authorization: 'Bearer ' + jwt('stranger@example.com')}})
  ok('a signed-in stranger sees no checks or settings', (await strangerChecks.json()).length === 0)
  await browser.close()
}
